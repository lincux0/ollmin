async (page) => {
  const checks=[]; const check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
  await page.setViewportSize({width:1180,height:820});await page.reload();await page.locator('.workspace-hero').waitFor();
  const input=page.getByRole('textbox',{name:'输入消息',exact:true});
  await page.locator('.session-main').click();await page.locator('[data-message-id="u0"]').waitFor();
  const nav=page.getByRole('navigation',{name:'会话回合'});await nav.waitFor();
  check(await nav.locator('button').count()===12,'只显示12个已加载用户回合');
  await nav.locator('button').nth(2).click();
  await page.getByRole('button',{name:'回到最新 ↓',exact:true}).waitFor();
  const first=page.locator('[data-message-id="u2"]');const list=page.locator('.message-list');
  const offset=()=>first.evaluate(el=>el.getBoundingClientRect().top-document.querySelector('.message-list').getBoundingClientRect().top);
  const anchored=async(value)=>page.waitForFunction(value=>Math.abs(document.querySelector('[data-message-id="u2"]').getBoundingClientRect().top-document.querySelector('.message-list').getBoundingClientRect().top-value)<3,value);
  await page.waitForFunction(()=>document.querySelector('.turn-navigator-item[aria-current="location"]')?.getAttribute('aria-label')?.startsWith('第 3 '));
  check(Math.abs(await offset()-12)<3,'回合定位与当前标记');
  check(await page.evaluate(()=>window.__REQUESTS__.length)===0,'定位不生成请求');
  await nav.locator('button').nth(2).focus();
  check(await page.locator('.turn-navigator-preview').isVisible(),'键盘focus显示问题摘要');
  const before=await offset();await input.fill(Array(7).fill('阅读草稿').join('\n'));
  await anchored(before);check(Math.abs(await offset()-before)<3,'输入增高维持阅读锚点');
  await page.locator('[data-message-id="a0"] summary').evaluate(el=>el.click());await page.waitForFunction(()=>document.querySelector('[data-message-id="a0"] details').open);await anchored(before);
  check(Math.abs(await offset()-before)<3,'展开上方思考维持阅读锚点');
  await page.locator('[data-message-id="a0"] summary').evaluate(el=>el.click());await page.waitForFunction(()=>!document.querySelector('[data-message-id="a0"] details').open);await anchored(before);
  check(Math.abs(await offset()-before)<3,'收起上方思考维持阅读锚点');
  await page.getByRole('separator',{name:'正文宽度'}).press('ArrowLeft');await anchored(before);
  check(Math.abs(await offset()-before)<3,'正文宽度变化维持阅读锚点');
  check(await first.evaluate(el=>getComputedStyle(el).borderRadius==='20px'&&getComputedStyle(el).boxShadow==='none'),'用户气泡R20无阴影');
  await first.getByRole('button',{name:'复制问题',exact:true}).click();await first.getByRole('button',{name:'已复制问题',exact:true}).waitFor();
  check(await page.evaluate(()=>window.__COPIES__.at(-1))==='第3回合问题','复制问题只复制正文');
  await first.getByRole('button',{name:'复制问题',exact:true}).waitFor();checks.push('复制成功短暂反馈恢复');
  await page.evaluate(()=>window.__FIXTURE__.copyError=true);await first.getByRole('button',{name:'复制问题',exact:true}).click();await first.getByRole('alert').waitFor();
  check(await first.getByRole('button',{name:'已复制问题',exact:true}).count()===0,'复制失败不显示成功');
  await page.evaluate(()=>window.__FIXTURE__.copyError=false);
  await nav.locator('button').first().click();const answer=page.locator('[data-message-id="a0"]');
  check(await answer.locator('img,script').count()===0&&await answer.locator('a[href^="javascript:"]').count()===0,'代码和危险链接安全渲染');
  check(await answer.locator('code.inline-code').count()===1,'行内代码节点');
  await answer.getByRole('button',{name:'复制代码',exact:true}).click();await answer.getByRole('button',{name:'已复制代码',exact:true}).waitFor();
  check((await page.evaluate(()=>window.__COPIES__.at(-1))).startsWith('const html ='),'代码独立复制');
  await answer.locator('summary').evaluate(el=>el.click());await answer.getByRole('button',{name:'复制思考过程',exact:true}).click();
  check((await page.evaluate(()=>window.__COPIES__.at(-1))).startsWith('合成思考。'),'思考独立复制');
  await page.getByRole('button',{name:'回到最新 ↓',exact:true}).click();await page.waitForTimeout(100);
  check(await list.evaluate(el=>el.scrollHeight-el.scrollTop-el.clientHeight<3),'回到最新恢复跟随');
  await input.fill('');await page.keyboard.press('Control+n');await page.locator('.workspace-hero').waitFor();
  check(await nav.count()===0,'新会话清理旧回合轨道');
  await input.fill('合成流');await input.press('Enter');await page.waitForFunction(()=>window.__REQUESTS__.length===1);
  const emit=async(payload)=>page.evaluate(payload=>window.__emit({request_id:window.__REQUESTS__[0].requestId,thinking:'',content:'',done:false,...payload}),payload);
  await emit({thinking:'合成流思考'});const streaming=page.locator('.assistant.streaming');await streaming.locator('summary').waitFor();
  check(await streaming.locator('details').getAttribute('open')!==null,'流中思考初始展开');
  await streaming.locator('summary').click();await emit({thinking:'后续思考',content:'~~~js\nconst n=1;'});
  await streaming.locator('pre code').waitFor();
  check(await streaming.locator('details').getAttribute('open')===null,'手动收起不被流事件重开');
  check(await streaming.locator('pre code').count()===1,'未闭合围栏稳定显示');
  await emit({content:'\n~~~',done:true});await page.getByRole('button',{name:'发送',exact:true}).waitFor();
  await page.locator('.assistant.done details').waitFor({state:'attached'});check(await page.locator('.assistant.done details').getAttribute('open')===null,'终态不覆盖思考手动选择');
  await page.screenshot({path:'D:/ollmin/output/playwright/dsh-phase45/phase4-verified.png'});
  return {checks,count:checks.length,scope:'Synthetic browser IPC only'};
}
